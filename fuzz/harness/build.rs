//! Every module the node binary declares (`mod NAME;` in crates/islandmail-node/src/main.rs) is compiled into this
//! library, so a module added to the node needs no edit here (a missing one broke the fuzz build before).
use std::path::PathBuf;

fn main() {
    let src = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../crates/islandmail-node/src");
    let src = src.canonicalize().unwrap_or_else(|e| panic!("node sources at {}: {e}", src.display()));
    let main = src.join("main.rs");
    println!("cargo:rerun-if-changed={}", main.display());
    let text = std::fs::read_to_string(&main).unwrap_or_else(|e| panic!("reading {}: {e}", main.display()));
    let mut out = String::from("// Generated by build.rs from the node's main.rs: one module per `mod NAME;` there.\n");
    let mut n = 0;
    let mut sources = String::new();
    for line in text.lines() {
        let Some(name) = line.trim().strip_prefix("mod ").and_then(|r| r.strip_suffix(';')) else { continue };
        let file = src.join(format!("{name}.rs"));
        assert!(file.is_file(), "the node declares `mod {name};` but {} is missing", file.display());
        println!("cargo:rerun-if-changed={}", file.display());
        sources += &std::fs::read_to_string(&file).unwrap();
        out += &format!("#[path = {:?}]\npub mod {name};\n", file.to_str().expect("UTF-8 path"));
        n += 1;
    }
    assert!(n > 0, "found no `mod NAME;` lines in {}", main.display());
    // The modules need the node's dependencies (those main.rs alone uses aside): name any this manifest lacks,
    // instead of a wall of E0433s.
    let manifest = |p: &std::path::Path| {
        println!("cargo:rerun-if-changed={}", p.display());
        let text = std::fs::read_to_string(p).unwrap_or_else(|e| panic!("reading {}: {e}", p.display()));
        let mut deps = Vec::new();
        let mut on = false;
        for l in text.lines().map(str::trim) {
            if l.starts_with('[') {
                on = l == "[dependencies]" || (l.starts_with("[target.") && l.ends_with(".dependencies]"));
            } else if let Some((k, _)) = l.split_once('=').filter(|_| on && !l.starts_with('#')) {
                deps.push(k.trim().to_string());
            }
        }
        deps
    };
    let ours = manifest(&PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("Cargo.toml"));
    let missing: Vec<String> = manifest(&src.join("../Cargo.toml")).into_iter()
        .filter(|d| !ours.contains(d) && sources.contains(&format!("{}::", d.replace('-', "_")))).collect();
    assert!(missing.is_empty(), "fuzz/harness/Cargo.toml lacks the node's dependencies {missing:?}: copy them from \
             crates/islandmail-node/Cargo.toml");
    std::fs::write(PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("node_modules.rs"), out).unwrap();
}
